// `keys` 是**說明**，快捷鍵本身在各模式的 `onKey()`。兩邊不同步的症狀是
// 「畫面上寫的鍵按了沒反應」，改快捷鍵的時候一定要回來改這一份。
//
// 側欄只放得下前幾行（手機沒有鍵盤，那裡連側欄都不會畫），完整的一份在
// 按 `?` 叫出來的說明面板裡 —— 兩邊讀的是同一個陣列。
//
// ─── 一套共通的語言 ──────────────────────────────────────────────────────
//
// 同一個鍵在每個模式都做同一類的事，不然使用者等於每換一個模式就要重學：
//
//   Enter  這個畫面的**主要動作**（對答案／繼續／下一題／送出）
//   空白   有錄音就是錄音，沒有就跟 Enter 一樣
//   N      換一題／一句／一段（畫面上有那顆按鈕的模式才有）
//   P      播放（聽力的錄音、對話裡對方那句、跟讀的示範）
//   S      把英文唸出來（單字、參考答案、修正後的句子）
//   A      要一次 AI 的東西（修正或講評）—— 手動模式下最常按的那顆
//   H      提示／看參考說法
//   T      看原文（聽力）
//   1–4    選項
//
// 單字卡沒有 N：它是一副有順序的牌組（到期的優先），「跳過這張」會讓
// 「今天練了幾張」對不起來 —— 沒有那顆按鈕，所以也不給那個鍵。

/**
 * 不分模式都能按的鍵。實作在 `app.js`（模式的 onKey 之前先問這一份）。
 *
 * 為什麼是 `[` `]` 而不是數字：數字鍵在四個模式裡是「選第幾個選項」，
 * 搶過來的話作答會變成換分頁 —— 而那是最不能出錯的一個鍵。
 */
export const GLOBAL_KEYS = [
  ['?', '這張快捷鍵表'],
  ['[', '上一個模式'],
  [']', '下一個模式'],
  ['Esc', '關閉說明'],
];

/** 會累積每日進度的模式（設定頁不算）。順序就是畫面上的順序。 */
export const PRACTICE_MODES = MODES.filter((m) => m.unit);

export const MODE_IDS = MODES.map((m) => m.id);

export function modeMeta(id) {
  return MODES.find((m) => m.id === id) ?? { id, label: id, icon: '', subtitle: '' };
}
