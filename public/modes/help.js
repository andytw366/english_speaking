// ─── 鍵盤 ────────────────────────────────────────────────────────────────
//
// 快捷鍵表本身在按 `?` 叫出來的面板裡（那一份跟著模式換）。這裡放的是
// 「為什麼每個模式的鍵都長一樣」—— 那件事在面板上寫不下。
function keysCard() {
  return h('div', { class: 'card' },
    h('p', { class: 'card__title' }, '⌨️ 鍵盤'),
    p('每個模式有哪些鍵：桌機的左側欄常駐列出最常按的幾個，按 ', h('kbd', { class: 'kbd' }, '?'), ' 看完整的一份。'),

    qa('同一個鍵在每個模式都做同一件事嗎？',
      p('是。不然每換一個模式就要重學一次：'),
      bullets([
        'Enter：這個畫面的主要動作（對答案／繼續／下一題／送出）',
        '空白：有錄音就是錄音，沒有就跟 Enter 一樣',
        'N 換一題・P 播放・S 唸出英文・A 要一次 AI・H 提示・T 看原文・1–4 選項',
      ]),
      p('中翻英與情境對話的「對答案」是 ⌘/Ctrl + Enter —— 那兩個地方的 Enter 要留給換行。'),
    ),

    qa('打字的時候按到 N 會換題嗎？',
      p('不會。焦點在輸入框裡（或中文輸入法組字中）時一律不接快捷鍵，' +
        '按 ] 就是打出一個 ]。'),
    ),

    qa('不分模式的鍵',
      bullets(GLOBAL_KEYS.map(([key, what]) => `${key}：${what}`)),
      p(`首頁另外有 1–${PRACTICE_MODES.length}，直接跳到清單上的那個模式。`),
    ),
  );
}
