import { h, append } from '../lib/dom.js';
import { grid } from '../lib/layout.js';
import { MODES, GLOBAL_KEYS, PRACTICE_MODES } from '../lib/modes.js';

export const meta = { id: 'help', label: '說明', icon: '❓' };

// 這一頁存在的理由：**設定頁與各個練習畫面原本背著整份說明書。**
//
// 每一段小字單獨看都有道理（「這個選項選了會怎樣」「這份資料清掉會怎樣」），
// 但加起來的結果是設定頁上一半的像素都在講解，而真正要按的控制項被擠得很散。
// 更糟的是那些字**每次進設定頁都在那裡** —— 第一次有用，第二十次只是噪音。
//
// 所以規則改成這樣：
//   畫面上留下的，是「現在這一刻要做決定時需要知道的事」（一句話講完）
//   搬到這裡的，是「想弄懂為什麼時才會找」的事（想找的人一定找得到）
//
// 排版是 `<details>` 問答：全部收起來，標題就是問題本身。
// 攤開來寫成長文的話，這一頁會變成另一個沒有人讀的地方。

let root = null;

export async function mount(container) {
  root = container;
  render();
  return () => { root = null; };
}

/** 一組問答。標題就是問題本身，答案收起來 —— 一次只讀想讀的那一題。 */
function qa(question, ...answer) {
  return h('details', { class: 'qa' },
    h('summary', { class: 'qa__q' }, question),
    h('div', { class: 'qa__a' }, answer.flat().filter(Boolean)),
  );
}

function p(...text) {
  return h('p', { class: 'qa__p' }, text.flat().filter(Boolean));
}

function bullets(items) {
  return h('ul', { class: 'qa__list' }, items.map((t) => h('li', {}, t)));
}

/** 「去那一頁」的按鈕。設定頁是最常被指過去的地方。 */
function goButton(id, label) {
  return h('button', {
    class: 'btn btn--ghost',
    onclick: () => window.dispatchEvent(new CustomEvent('switch-mode', { detail: id })),
  }, label);
}

function render() {
  if (!root) return;
  append(grid(root), startCard(), aiCard(), dataCard(), troubleCard(), keysCard());
}

